def gold_checks() -> tuple[pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    gold = ROOT / "data" / "generated" / "gold" / "fact_anggaran.parquet"
    if not gold.exists():
        return pd.DataFrame(), pd.DataFrame(), {"status": "BELUM TERSEDIA"}
    frame = pd.read_parquet(gold)
    schema = []
    for column in frame.columns:
        series = frame[column]
        example = series.dropna().iloc[0] if not series.dropna().empty else None
        schema.append(
            {
                "column": column,
                "dtype": str(series.dtype),
                "null_count": int(series.isna().sum()),
                "null_percent": round(float(series.isna().mean() * 100), 4),
                "unique_count": int(series.nunique(dropna=True)),
                "example": example,
            }
        )
    lineage_columns = ["source_file", "source_sheet", "source_row", "item_id", "run_id", "created_at"]
    lineage = []
    for column in lineage_columns:
        filled = int(frame[column].notna().sum()) if column in frame.columns else 0
        lineage.append(
            {
                "lineage_attribute": column,
                "filled_rows": filled,
                "empty_rows": len(frame) - filled,
                "completeness_percent": round(filled / len(frame) * 100, 4) if len(frame) else 0,
                "status": "VERIFIED" if column in frame.columns else "BELUM TERSEDIA",
            }
        )
    grain_columns = [column for column in ("item_id", "kode_iku") if column in frame.columns]
    duplicates = int(frame.duplicated(grain_columns).sum()) if grain_columns else None
    weighted = float(frame["jumlah_weighted_iku"].sum()) if "jumlah_weighted_iku" in frame.columns else None
    total = float(frame["jumlah"].sum()) if "jumlah" in frame.columns else None
    checks = {
        "status": "VERIFIED",
        "row_count": len(frame),
        "column_count": len(frame.columns),
        "grain_columns": grain_columns,
        "duplicate_grain_rows": duplicates,
        "jumlah_sum": total,
        "jumlah_weighted_iku_sum": weighted,
        "allocation_weight_sum_by_item_available": "allocation_weight" in frame.columns,
        "sample_seed": SEED,
    }
    return pd.DataFrame(schema), pd.DataFrame(lineage), checks


