def rel(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def run_text(command: list[str]) -> str:
    try:
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
        return result.stdout.strip() or result.stderr.strip() or "NOT_AVAILABLE"
    except OSError:
        return "NOT_AVAILABLE"


def dump_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2, ensure_ascii=False, default=str), encoding="utf-8")


def write_table(frame: pd.DataFrame, stem: str, title: str, label: str, source: str) -> None:
    csv_path = TABLES / f"{stem}.csv"
    tex_path = TABLES / f"{stem}.tex"
    frame.to_csv(csv_path, index=False, encoding="utf-8-sig")
    safe = frame.copy()
    for column in safe.columns:
        safe[column] = safe[column].astype(str).str.replace("&", r"\&", regex=False)
    body = safe.to_latex(index=False, escape=False, longtable=True)
    tex = (
        "% Generated by outputs/bab4_evidence/scripts/audit_bab4_evidence.py\n"
        f"% Title: {title}\n% Label: {label}\n% Source: {source}\n"
        "\\begingroup\n\\scriptsize\n"
        + body
        + "\\endgroup\n"
    )
    tex_path.write_text(tex, encoding="utf-8")


def profile_workbook(path: Path, dataset_type: str) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    workbook = openpyxl.load_workbook(path, read_only=False, data_only=False)
    workbook_row = {
        "alias_file": path.name,
        "relative_path": rel(path),
        "jenis_dataset": dataset_type,
        "size_bytes": path.stat().st_size,
        "modified_at": datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(),
        "sheet_count": len(workbook.worksheets),
        "sha256": sha256(path),
        "sha256_short": sha256(path)[:16],
        "extracted_at": STAMP,
    }
    sheets: list[dict[str, Any]] = []
    for sheet in workbook.worksheets:
        filled = formula = merged = fills = bold = borders = 0
        number_formats: set[str] = set()
        for row in sheet.iter_rows():
            for cell in row:
                if cell.value is not None:
                    filled += 1
                if isinstance(cell.value, str) and cell.value.startswith("="):
                    formula += 1
                if cell.fill and cell.fill.fill_type:
                    fills += 1
                if cell.font and cell.font.bold:
                    bold += 1
                if cell.border and any(
                    getattr(edge, "style", None)
                    for edge in (cell.border.left, cell.border.right, cell.border.top, cell.border.bottom)
                ):
                    borders += 1
                if cell.number_format:
                    number_formats.add(cell.number_format)
        sheet_name = sheet.title.lower()
        if "rab" in sheet_name:
            role = "main_rab"
        elif any(token in sheet_name for token in ("detail", "belanja", "perjalanan", "jasa", "sewa")):
            role = "detail_support"
        elif any(token in sheet_name for token in ("nomen", "referensi", "reference", "iku")):
            role = "reference"
        elif any(token in sheet_name for token in ("template", "format")):
            role = "template"
        elif any(token in sheet_name for token in ("rekon", "recon")):
            role = "reconciliation"
        else:
            role = "unknown"
        sheets.append(
            {
                "file": path.name,
                "sheet": sheet.title,
                "role": role,
                "rows": sheet.max_row,
                "columns": sheet.max_column,
                "filled_cells": filled,
                "formula_cells": formula,
                "merged_ranges": len(sheet.merged_cells.ranges),
                "filled_style_cells": fills,
                "bold_cells": bold,
                "border_cells": borders,
                "number_format_count": len(number_formats),
                "structure_note": "profil aktual dengan openpyxl; formula tidak dihitung ulang",
            }
        )
    workbook.close()
    workbook_row["filled_cells"] = sum(item["filled_cells"] for item in sheets)
    workbook_row["formula_cells"] = sum(item["formula_cells"] for item in sheets)
    workbook_row["merged_ranges"] = sum(item["merged_ranges"] for item in sheets)
    return workbook_row, sheets


def active_sources() -> list[tuple[Path, str]]:
    pointer = ROOT / "outputs" / "reports" / "active_excel_lakehouse_dataset.json"
    if not pointer.exists():
        return []
    payload = json.loads(pointer.read_text(encoding="utf-8"))
    sources = []
    for item in payload.get("files", []):
        path = ROOT / item["path"]
        if path.exists():
            sources.append((path, item.get("jenis_dataset", "unknown")))
    return sources


def artifact_rows() -> list[dict[str, Any]]:
    roots = [ROOT / "data" / "generated", ROOT / "outputs" / "reports"]
    rows = []
    for base in roots:
        if not base.exists():
            continue
        for path in base.rglob("*"):
            if not path.is_file() or "bab4_evidence" in path.parts:
                continue
            row: dict[str, Any] = {
                "path": rel(path),
                "layer": "reports" if "reports" in path.parts else next((part for part in ("bronze", "silver", "gold") if part in path.parts), "generated"),
                "extension": path.suffix.lower(),
                "size_bytes": path.stat().st_size,
                "modified_at": datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(),
                "sha256": sha256(path),
                "row_count": None,
                "column_count": None,
                "status": "VERIFIED",
            }
            try:
                if path.suffix.lower() == ".parquet":
                    frame = pd.read_parquet(path)
                    row["row_count"], row["column_count"] = len(frame), len(frame.columns)
                elif path.suffix.lower() == ".csv":
                    frame = pd.read_csv(path, nrows=5)
                    row["column_count"] = len(frame.columns)
            except Exception as exc:
                row["status"] = f"PARTIAL: {type(exc).__name__}"
            rows.append(row)
    return rows


