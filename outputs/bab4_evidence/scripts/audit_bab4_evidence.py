def main() -> int:
    workbooks: list[dict[str, Any]] = []
    sheets: list[dict[str, Any]] = []
    for path, dataset_type in active_sources():
        workbook_row, sheet_rows = profile_workbook(path, dataset_type)
        workbooks.append(workbook_row)
        sheets.extend(sheet_rows)
    workbook_frame = pd.DataFrame(workbooks)
    sheet_frame = pd.DataFrame(sheets)
    artifact_frame = pd.DataFrame(artifact_rows())
    environment_frame = environment_inventory()
    schema_frame, lineage_frame, gold_data = gold_checks()

    if not workbook_frame.empty:
        write_table(workbook_frame, "tab_411_inventaris_workbook", "Inventarisasi Workbook Sumber", "tab:hasil-inventaris-workbook", "active_excel_lakehouse_dataset.json")
    if not sheet_frame.empty:
        write_table(sheet_frame, "tab_411_struktur_sheet", "Karakteristik Struktur per Sheet", "tab:hasil-struktur-sheet", "workbook sumber aktif")
    write_table(environment_frame, "environment_inventory", "Spesifikasi Lingkungan Implementasi", "tab:spesifikasi-lingkungan", "runtime inspection")
    if not artifact_frame.empty:
        write_table(artifact_frame, "artifact_manifest", "Manifest Artefak", "tab:manifest-artefak", "data/generated and outputs/reports")
    if not schema_frame.empty:
        write_table(schema_frame, "tab_413_fact_anggaran_schema", "Struktur Aktual fact_anggaran", "tab:struktur-aktual-fact-anggaran", "data/generated/gold/fact_anggaran.parquet")
    if not lineage_frame.empty:
        write_table(lineage_frame, "tab_413_kelengkapan_lineage", "Kelengkapan Data Lineage", "tab:kelengkapan-lineage", "data/generated/gold/fact_anggaran.parquet")

    dump_json(OUT / "00_manifest" / "gold_checks.json", gold_data)
    dump_json(OUT / "00_manifest" / "audit_metadata.json", {"timestamp": STAMP, "seed": SEED, "script": rel(Path(__file__))})
    figures = make_figures(workbook_frame, sheet_frame, lineage_frame)
    write_supporting_docs(artifact_frame, gold_data, figures)

    status = "VERIFIED"
    if workbook_frame.empty or artifact_frame.empty:
        status = "PARTIAL"
    final_report = {
        "status": "PASS WITH LIMITATIONS" if status == "VERIFIED" else "INCOMPLETE",
        "audit_status": status,
        "generated_at": STAMP,
        "script": rel(Path(__file__)),
        "source_workbooks": len(workbook_frame),
        "artifacts": len(artifact_frame),
        "figures": figures,
        "limitations_file": rel(OUT / "00_manifest" / "limitations.md"),
        "user_modified_files_preserved": True,
        "production_sources_modified": False,
    }
    dump_json(OUT / "final_validation_report.json", final_report)
    (OUT / "final_validation_report.md").write_text(
        "# Final validation report\n\n"
        f"- Status: **{final_report['status']}**\n"
        f"- Audit status: `{status}`\n"
        f"- Generated: `{STAMP}`\n"
        f"- Source workbooks profiled: `{len(workbook_frame)}`\n"
        f"- Artifacts inventoried: `{len(artifact_frame)}`\n"
        "- Production sources modified: `False`\n"
        "- UAT: `BELUM TERSEDIA` unless evidence is supplied separately\n",
        encoding="utf-8",
    )
    print(json.dumps(final_report, ensure_ascii=False, indent=2))
    return 0


